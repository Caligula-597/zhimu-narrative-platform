/** Canonical public code (resolves deprecated aliases). */
export function canonicalPlayableErrorCode(code) {
  const raw = String(code || "");
  if (raw === "WRONG_STAGE") return "NOT_CURRENT_STAGE";
  if (raw === "MECHANISM_ALREADY_SETTLED") return "ALREADY_SETTLED";
  return raw;
}
